# Input contract for the Rj adapter shipped as a Pj resource.
library(Pj);library(Rj)
sys.source(system.file('rj','mzPj_rj_support.R',package='Pj'),envir=environment())
opts<-getFromNamespace('RjOptions','Rj')$new(code='',R='bundled')
host<-jmvcore::Group$new(options=opts,name='test')
reject<-function(expr)stopifnot(inherits(tryCatch(force(expr),error=identity),'error'))
reject(mzPjRjHost(NULL,iris))
reject(mzPjRjHost(host,iris,python='invalid'))
reject(mzPjRjHost(host,iris,source='invalid'))
reject(mzPjRjHost(host,data.frame(x=character())))
reject(mzPjRjHost(host,iris,variables='Species'))
reject(mzPjRjHost(host,iris,variables=c('Sepal.Length','Sepal.Length')))
fixture<-mzPjRjHost(host,iris,source='example')
stopifnot(nrow(fixture$data)==8L,identical(names(fixture$data),c('Before','After')))
